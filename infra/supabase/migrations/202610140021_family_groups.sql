-- ── Family groups ──────────────────────────────────────────────────────────────────────────
create table if not exists public.accounts (
  sub varchar(128) primary key,
  role varchar(16) not null,
  display_name varchar(80) not null,
  created_at timestamptz not null
);

create table if not exists public.care_groups (
  group_id varchar(64) primary key,
  person_id varchar(64) not null unique references public.people(person_id),
  linked_via varchar(32) not null,
  created_by varchar(128) not null,
  created_at timestamptz not null
);

create table if not exists public.group_members (
  member_id varchar(64) primary key,
  group_id varchar(64) not null references public.care_groups(group_id),
  sub varchar(128) not null,
  relationship varchar(40) not null,
  role varchar(16) not null,
  status varchar(16) not null,
  created_at timestamptz not null,
  approved_by varchar(128),
  approved_at timestamptz,
  constraint uq_group_members_group_sub unique (group_id, sub)
);
create index if not exists ix_group_members_group_id on public.group_members(group_id);
create index if not exists ix_group_members_sub on public.group_members(sub);

create table if not exists public.family_pins (
  pin_id varchar(64) primary key,
  purpose varchar(16) not null,
  pin_hash varchar(64) not null,
  person_id varchar(64) references public.people(person_id),
  group_id varchar(64) references public.care_groups(group_id),
  created_by varchar(128) not null,
  created_at timestamptz not null,
  expires_at timestamptz not null,
  used_at timestamptz,
  constraint uq_family_pins_purpose_hash unique (purpose, pin_hash)
);
create index if not exists ix_family_pins_person_id on public.family_pins(person_id);
create index if not exists ix_family_pins_group_id on public.family_pins(group_id);

create table if not exists public.pin_attempts (
  attempt_id integer generated by default as identity primary key,
  sub varchar(128) not null,
  succeeded boolean not null,
  attempted_at timestamptz not null
);
create index if not exists ix_pin_attempts_sub_at on public.pin_attempts(sub, attempted_at);

